export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.zh;
  return (key, vars) => {
    let s = table[key];
    if (s === undefined) s = STRINGS.zh[key];
    if (s === undefined) return key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    }
    return s;
  };
}
